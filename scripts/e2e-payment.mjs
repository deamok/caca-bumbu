import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, locale: 'id-ID', timezoneId: 'Asia/Jakarta' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Coba dengan data contoh' }).click();
await page.waitForTimeout(500);
const state = await page.evaluate(() => JSON.parse(localStorage.getItem('caca-bumbu:state:v1')));
const closed = state.consignments.find(c => c.status === 'selesai' && c.items.reduce((s,i) => s + i.soldQty*i.price, 0) > 70000);
assert.ok(closed);
await page.goto('http://127.0.0.1:4173/#/titip/' + closed.id, { waitUntil: 'networkidle' });
await page.waitForTimeout(400);
assert.ok(await page.getByText('Ada sisa bayar').first().isVisible());
const beforePayments = state.payments.length;
await page.getByRole('button', { name: 'Catat pelunasan' }).click();
await page.waitForTimeout(300);
await page.getByRole('button', { name: 'Simpan pembayaran' }).click();
await page.waitForTimeout(500);
const updated = await page.evaluate(() => JSON.parse(localStorage.getItem('caca-bumbu:state:v1')));
assert.equal(updated.payments.length, beforePayments + 1, 'payment added');
const remaining = closed.items.reduce((s,i) => s + i.soldQty*i.price, 0) - updated.payments.filter(p => p.refId === closed.id).reduce((s,p) => s + p.amount, 0);
assert.equal(remaining, 0, 'fully paid');
console.log('closed consignment payment OK, errors', errors);
await browser.close();
