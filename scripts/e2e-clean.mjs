import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const BASE = 'http://127.0.0.1:4173/';
const browser = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, locale: 'id-ID', timezoneId: 'Asia/Jakarta' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(BASE, { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Mulai dari nol' }).click();
await page.waitForTimeout(600);
let state = await page.evaluate(() => JSON.parse(localStorage.getItem('caca-bumbu:state:v1')));
assert.equal(state.products.length, 10);
assert.equal(state.products[0].stock, 0);
assert.equal(state.meta.onboarded, true);
console.log('clean onboarding OK');
await page.goto(BASE + '#/jual', { waitUntil: 'networkidle' });
assert.ok(await page.getByText('Semua stok masih kosong').isVisible());
assert.equal(await page.locator('.add-product-btn:not([disabled])').count(), 0);
console.log('empty stock guard OK');
// Atur stok from product page
await page.goto(BASE + '#/produk', { waitUntil: 'networkidle' });
await page.locator('.product-table__row').first().click();
await page.waitForTimeout(300);
await page.locator('#product-stock').fill('10');
await page.getByRole('button', { name: 'Simpan perubahan' }).click();
await page.waitForTimeout(500);
state = await page.evaluate(() => JSON.parse(localStorage.getItem('caca-bumbu:state:v1')));
const stocked = state.products.find(p => p.stock === 10);
assert.ok(stocked, 'stok awal tersimpan');
console.log('stocked product', stocked.name);
console.log('edit stock OK');
// Jual
await page.goto(BASE + '#/jual', { waitUntil: 'networkidle' });
await page.locator('.add-product-btn:not([disabled])').first().click();
await page.locator('.cart-bar .btn').click();
await page.getByRole('button', { name: 'Simpan penjualan' }).click();
await page.waitForTimeout(500);
state = await page.evaluate(() => JSON.parse(localStorage.getItem('caca-bumbu:state:v1')));
assert.equal(state.sales.length, 1, 'sale created');
assert.equal(state.products.find(p => p.id === stocked.id).stock, 9);
console.log('clean sale OK');
// Add warung
await page.goto(BASE + '#/warung?new=1', { waitUntil: 'networkidle' });
await page.waitForTimeout(400);
assert.ok(await page.getByText('Tambah warung').first().isVisible());
await page.locator('#warung-name').fill('Warung Baru');
await page.locator('#warung-owner').fill('Bu Baru');
await page.locator('#warung-phone').fill('081211122233');
await page.getByRole('button', { name: 'Tambah warung', exact: true }).last().click();
await page.waitForTimeout(500);
state = await page.evaluate(() => JSON.parse(localStorage.getItem('caca-bumbu:state:v1')));
assert.equal(state.warungs.length, 1, 'warung added');
console.log('add warung OK');
// Add titipan via form
await page.goto(BASE + '#/titip/baru?warung=' + state.warungs[0].id, { waitUntil: 'networkidle' });
await page.waitForTimeout(300);
await page.locator('.pick-row .add-product-btn:not([disabled])').first().click();
await page.locator('.form-dock .btn').click();
await page.waitForTimeout(700);
state = await page.evaluate(() => JSON.parse(localStorage.getItem('caca-bumbu:state:v1')));
assert.equal(state.consignments.length, 1, 'titipan created');
assert.equal(state.consignments[0].items[0].sentQty, 1);
assert.equal(state.products.find(p => p.id === stocked.id).stock, 8);
console.log('clean titipan OK');
assert.deepEqual(errors, []);
console.log('CLEAN FLOW OK');
await browser.close();